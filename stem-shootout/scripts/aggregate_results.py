"""Combine every song's results.json into one cross-song leaderboard.

Each song's own results.md (written by run_shootout.py) is the detailed,
single-song view. This script answers the question one song can't: which
model is actually best *on average*, across every song tested so far —
and where does it fall apart on a particular one? Run it any time after
adding a new song or model; it only reads existing results.json files, it
doesn't run anything.

Usage: python aggregate_results.py [--songs-dir ../data/songs] [--output ../LEADERBOARD.md]
"""
from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

STEMS = ["vocals", "drums", "bass", "other", "instrumental"]


def load_all_results(songs_dir: Path) -> dict[str, dict[str, dict]]:
    """Returns {song_name: {model: {stem: sdr}}}"""
    out = {}
    for song_dir in sorted(songs_dir.iterdir()):
        results_path = song_dir / "results.json"
        config_path = song_dir / "config.json"
        if not results_path.exists() or not config_path.exists():
            continue
        song_name = json.loads(config_path.read_text())["song_name"]
        per_model = {}
        for entry in json.loads(results_path.read_text()):
            per_model[entry["model"]] = {
                stem: vals["SDR"] for stem, vals in entry["stems"].items()
            }
        out[song_name] = per_model
    return out


def render(all_results: dict[str, dict[str, dict]]) -> str:
    songs = list(all_results.keys())
    models = sorted({m for song in all_results.values() for m in song})

    lines = ["# Cross-song leaderboard", "",
              "Auto-generated by `aggregate_results.py` — do not hand-edit, regenerate "
              "it after adding a new song or model instead.", "",
              f"Songs covered: {', '.join(songs)}.", ""]

    for stem in STEMS:
        rows = []
        for model in models:
            per_song = []
            for song in songs:
                v = all_results.get(song, {}).get(model, {}).get(stem)
                per_song.append(v)
            scored = [v for v in per_song if v is not None]
            if not scored:
                continue
            avg = statistics.mean(scored)
            rows.append((model, per_song, avg))
        if not rows:
            continue

        rows.sort(key=lambda r: r[2], reverse=True)
        lines.append(f"## {stem}")
        lines.append("")
        lines.append("| Model | " + " | ".join(songs) + " | **Average** |")
        lines.append("|---" * (len(songs) + 2) + "|")
        for model, per_song, avg in rows:
            cells = [f"{v:.2f}" if v is not None else "—" for v in per_song]
            lines.append(f"| {model} | " + " | ".join(cells) + f" | **{avg:.2f}** |")
        lines.append("")

    lines.append(
        "SDR in dB, higher is better, median across 1s windows (museval). "
        "A model missing a row for a given stem means it doesn't produce that "
        "stem at all (e.g. a 2-stem vocal/instrumental model has no drums/bass/other row)."
    )
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--songs-dir", type=Path, default=Path(__file__).parent.parent / "data" / "songs")
    ap.add_argument("--output", type=Path, default=Path(__file__).parent.parent / "LEADERBOARD.md")
    args = ap.parse_args()

    all_results = load_all_results(args.songs_dir)
    report = render(all_results)
    args.output.write_text(report)
    print(report)


if __name__ == "__main__":
    main()
